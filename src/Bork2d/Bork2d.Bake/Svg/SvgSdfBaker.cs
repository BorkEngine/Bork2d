using System.Globalization;
using System.Numerics;
using Bork2d.Bake.Textures;
using Bork2d.Engine.Assets;

namespace Bork2d.Bake.Svg;

/// <summary>
/// Bakes a task-1 <see cref="SvgArtwork"/> into a linear MSDF KTX2 texture.
/// </summary>
/// <remarks>
/// <para>
/// The artboard is sized from the resolution, range, and padding: the margin is <c>range + padding</c>
/// pixels on every side, the longer artboard axis fills the remaining resolution, and the shorter axis
/// keeps the artboard aspect. The visible content is exactly one world unit high after
/// <see cref="SvgSdfBakeResult.SpriteScale"/> is applied.
/// </para>
/// <para>
/// The field is generated by SeasonMSDF, validated against the exact shape distance, expanded into
/// the shared distance-preserving mip chain, and written as one complete KTX2 payload. A content
/// problem reports the matching <c>BK92xx</c> diagnostic and returns <see langword="null"/>; the
/// method does not throw for authored values.
/// </para>
/// </remarks>
internal static class SvgSdfBaker
{
    /// <summary>Bakes one artwork into a complete KTX2 payload.</summary>
    /// <param name="artwork">The normalized task-1 artwork.</param>
    /// <param name="options">The authored bake options.</param>
    /// <param name="diagnostics">The diagnostic bag to report a failure to.</param>
    /// <returns>The baked texture and its descriptor values, or <see langword="null"/> on failure.</returns>
    /// <exception cref="ArgumentNullException">An argument is <see langword="null"/>.</exception>
    internal static SvgSdfBakeResult? Bake(
        SvgArtwork artwork,
        SvgSdfBakeOptions options,
        SvgDiagnostics diagnostics)
    {
        ArgumentNullException.ThrowIfNull(artwork);
        ArgumentNullException.ThrowIfNull(diagnostics);

        if (!Enum.IsDefined(options.Compression))
        {
            diagnostics.Error(
                SvgDiagnosticCodes.SdfOptionsInvalid,
                string.Create(
                    CultureInfo.InvariantCulture,
                    $"The SDF compression value {(int)options.Compression} is not supported; use none or bc7."));
            return null;
        }

        if (options.Resolution <= 0 || options.Resolution > SvgSdfBakeOptions.MaxResolution)
        {
            diagnostics.Error(
                SvgDiagnosticCodes.SdfOptionsInvalid,
                string.Create(
                    CultureInfo.InvariantCulture,
                    $"The SDF resolution {options.Resolution} is outside 1..{SvgSdfBakeOptions.MaxResolution}."));
            return null;
        }

        if (options.Range <= 0)
        {
            diagnostics.Error(
                SvgDiagnosticCodes.SdfOptionsInvalid,
                string.Create(
                    CultureInfo.InvariantCulture,
                    $"The SDF range {options.Range} must be positive."));
            return null;
        }

        if (options.Padding < 0)
        {
            diagnostics.Error(
                SvgDiagnosticCodes.SdfOptionsInvalid,
                string.Create(
                    CultureInfo.InvariantCulture,
                    $"The SDF padding {options.Padding} must not be negative."));
            return null;
        }

        long inset = (long)options.Range + options.Padding;
        long usable = options.Resolution - (2 * inset);
        if (usable <= 0)
        {
            diagnostics.Error(
                SvgDiagnosticCodes.SdfOptionsInvalid,
                string.Create(
                    CultureInfo.InvariantCulture,
                    $"The SDF resolution {options.Resolution} leaves no usable artboard: the "
                    + $"range+padding margin is {inset} pixels on every side."));
            return null;
        }

        int insetPixels = (int)inset;
        double scale = (double)usable / Math.Max(artwork.Width, artwork.Height);
        double contentWidth = artwork.Width * scale;
        double contentHeight = artwork.Height * scale;
        if (!IsFinitePositive(scale)
            || !IsFinitePositive(contentWidth)
            || !IsFinitePositive(contentHeight))
        {
            diagnostics.Error(
                SvgDiagnosticCodes.SdfOptionsInvalid,
                string.Create(
                    CultureInfo.InvariantCulture,
                    $"The artboard content cannot be represented at resolution {options.Resolution}: the pixel scale ({scale:G6}) and content extent ({contentWidth:G6}x{contentHeight:G6}) must be finite and positive."));
            return null;
        }

        int textureWidth = TextureExtent(contentWidth, insetPixels, options.Resolution);
        int textureHeight = TextureExtent(contentHeight, insetPixels, options.Resolution);

        // The longer axis's content equals the usable extent exactly, but the double product can land
        // a hair below it; pin the long axis so the texture always reaches the resolution budget.
        if (artwork.Width >= artwork.Height)
        {
            textureWidth = options.Resolution;
        }

        if (artwork.Height >= artwork.Width)
        {
            textureHeight = options.Resolution;
        }

        // The result stores SpriteAsset.Scale as a Vector2, so the ratio must survive the float cast.
        double spriteScaleX = (double)textureWidth / contentHeight;
        double spriteScaleY = (double)textureHeight / contentHeight;
        float spriteScaleX32 = (float)spriteScaleX;
        float spriteScaleY32 = (float)spriteScaleY;
        if (!IsFinitePositive(spriteScaleX)
            || !IsFinitePositive(spriteScaleY)
            || !IsFinitePositive(spriteScaleX32)
            || !IsFinitePositive(spriteScaleY32))
        {
            diagnostics.Error(
                SvgDiagnosticCodes.SdfOptionsInvalid,
                string.Create(
                    CultureInfo.InvariantCulture,
                    $"The artboard cannot be represented as a 1-unit-high sprite at resolution {options.Resolution}: the sprite scale ({spriteScaleX:G6}, {spriteScaleY:G6}) must be finite and positive as a float."));
            return null;
        }

        MsdfField? field = MsdfField.Create(
            artwork,
            scale,
            insetPixels,
            textureWidth,
            textureHeight,
            options.Range,
            diagnostics);
        if (field is null)
        {
            return null;
        }

        if (!field.ValidateBase(diagnostics))
        {
            return null;
        }

        TextureLevel[] levels = TextureMipChain.Generate(
            field.Pixels,
            textureWidth,
            textureHeight,
            TextureChannelType.Rgb);
        if (!field.ValidateMipChain(levels, diagnostics))
        {
            return null;
        }

        TextureFormat format = options.Compression == SdfCompression.Bc7
            ? TextureFormat.CompRgba8
            : TextureFormat.Rgb8;
        TextureFormatInfo formatInfo = TextureFormatInfo.For(format);
        var storedLevels = new byte[levels.Length][];
        if (options.Compression == SdfCompression.Bc7)
        {
            for (int level = 0; level < levels.Length; level++)
            {
                storedLevels[level] = BcTextureEncoder.Encode(levels[level], format);
            }

            if (!SdfBc7Validator.Validate(field, levels, storedLevels, diagnostics))
            {
                return null;
            }
        }
        else
        {
            for (int level = 0; level < levels.Length; level++)
            {
                storedLevels[level] = levels[level].Pixels;
            }
        }

        byte[] payload = Ktx2Writer.Write(formatInfo, textureWidth, textureHeight, storedLevels);
        return new SvgSdfBakeResult(
            new BakedTexture(payload, format, (uint)levels.Length),
            textureWidth,
            textureHeight,
            contentWidth,
            contentHeight,
            scale,
            new Vector2(spriteScaleX32, spriteScaleY32));
    }

    private static bool IsFinitePositive(double value) => double.IsFinite(value) && value > 0;

    private static bool IsFinitePositive(float value) => float.IsFinite(value) && value > 0;

    private static int TextureExtent(double content, int inset, int resolution)
    {
        double extent = content + (2.0 * inset);
        int pixels = (int)Math.Ceiling(extent);
        return Math.Clamp(pixels, 1, resolution);
    }
}
